const TRANSLATIONS = {};

function registerTranslations(lang, dict) {
  TRANSLATIONS[lang] = { ...(TRANSLATIONS[lang] || {}), ...dict };
}

function detectLanguage() {
  const saved = localStorage.getItem("lang");
  if (saved && LANGUAGES.some((l) => l.code === saved)) return saved;
  const browserLangs = navigator.languages || [navigator.language];
  for (const bl of browserLangs) {
    const short = bl.slice(0, 2).toLowerCase();
    if (LANGUAGES.some((l) => l.code === short)) return short;
  }
  return "sv";
}

let currentLang = "sv";

function t(key, vars) {
  let str = (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || (TRANSLATIONS.sv && TRANSLATIONS.sv[key]) || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, v);
    }
  }
  return str;
}

